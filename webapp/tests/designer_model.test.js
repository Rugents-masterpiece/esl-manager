"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const M = fs.existsSync(require.resolve("../static/template-family.js").replace("template-family.js", "designer-model.js")) ? require("../static/designer-model.js") : {};
assert.equal(typeof M.createDocument, "function", "document defaults must be available");
const doc = M.createDocument("Cenovka", "2.13TFT-BW");
assert.deepEqual(doc, {schema_version:1,name:"Cenovka",model_id:"2.13TFT-BW",elements:[],sample_data:{}});
const copy = M.clone(doc); copy.sample_data.name = "Test";
assert.deepEqual(doc.sample_data, {});
console.log("designer model defaults: OK");
assert.equal(typeof M.add, "function", "element operations must be available");
const added = M.add(doc, "text");
assert.equal(doc.elements.length, 0);
const id = added.elements[0].id;
assert.equal(added.elements[0].font_size, 18);
const moved = M.move(added, id, 999, -20);
assert.equal(moved.elements[0].x, 130);
assert.equal(moved.elements[0].y, 0);
const resized = M.update(moved, id, {width:999,height:999,color:"#ff0000"});
assert.equal(resized.elements[0].width, 250);
assert.equal(resized.elements[0].x, 0);
assert.equal(resized.elements[0].color, "#000000");
const doubled = M.duplicate(added,id);
assert.equal(doubled.elements.length,2);
assert.notEqual(doubled.elements[1].id,id);
assert.equal(M.layer(doubled,id,1).elements[1].id,id);
assert.equal(M.remove(doubled,id).elements.length,1);
let full = doc;
for(let i=0;i<100;i++) full=M.add(full,"rectangle");
assert.throws(()=>M.add(full,"line"), /100/);
console.log("designer element operations: OK");
assert.equal(typeof M.History, "function", "history must be available");
const history=new M.History(doc);
history.set(added); history.set(moved);
assert.deepEqual(history.undo(),added); assert.deepEqual(history.redo(),moved);
history.undo(); history.set(doubled); assert.equal(history.canRedo,false);
const snapshot=history.document; snapshot.name="bad"; assert.equal(history.document.name,"Cenovka");
assert.equal(M.renderText({...added.elements[0],field:"price",prefix:"€ ",suffix:" / kg"},{price:0}),"€ 0 / kg");
assert.equal(M.renderText({...added.elements[0],field:"missing"},{}),"Názov produktu");
assert.deepEqual(M.validate(added),[]);
assert.ok(M.validate({...added,elements:[added.elements[0],added.elements[0]]}).length);
assert.ok(M.validate({...added,unknown:true}).length);
assert.ok(M.validate({...added,elements:[{...added.elements[0],field:"bad-field"}]}).length);
assert.ok(M.validate({...added,elements:[{...added.elements[0],x:-1}]}).length);
console.log("designer history, rendering and validation: OK");
assert.throws(()=>M.createDocument("Bad","__proto__"),/model/);
for(const invalid of [{id:"x".repeat(65)},{id:"   "}]) assert.ok(M.validate({...added,elements:[{...added.elements[0],...invalid}]}).length);
for(const sample_data of [{"bad-key":"x"},{ok:[]},{ok:{}},{ok:"x".repeat(2001)},{ok:Infinity},Object.fromEntries(Array.from({length:101},(_,i)=>[`k${i}`,i]))]) assert.ok(M.validate({...added,sample_data}).length,"reject unsafe sample values");
assert.deepEqual(M.validate({...added,sample_data:{price:0,flag:false,nothing:null,label:"Produkt"}}),[]);
const huge={...added,elements:Array.from({length:100},(_,i)=>({...added.elements[0],id:`id${i}`,text:"ž".repeat(2000)}))};
assert.ok(M.validate(huge).length,"reject document over UTF8 byte limit");
assert.ok(M.validate({...added,model_id:"constructor"}).length);
console.log("designer strict limits: OK");
const longName=M.update(added,id,{name:"n".repeat(200)});
assert.deepEqual(M.validate(M.duplicate(longName,id)),[],"duplicate keeps maximum-length names valid");
for(const type of ["text","rectangle","line"]) assert.deepEqual(M.validate(M.add(M.createDocument("Tag","2.9EPD-BWR"),type)),[]);
assert.equal(M.update(M.add(M.createDocument(),"text"),"element-1",{color:"#ff0000"}).elements[0].color,"#ff0000");
console.log("designer schema edge cases: OK");
